    public SerializedProperty sdfCutoutConcavityXProperty;
    public SerializedProperty sdfCutoutConcavityYProperty;
    public SerializedProperty sdfCutoutConcavityZProperty;
    public SerializedProperty sdfCutoutConcavityWProperty;
    public SerializedProperty sdfCutoutPositionProperty;
    public SerializedProperty sdfCutoutSizeProperty;
    public SerializedProperty sdfCutoutRotationProperty;
    public SerializedProperty outlineWidthProperty;
    public SerializedProperty proceduralGradientPositionProperty;
    public SerializedProperty radialGradientSizeProperty;
    public SerializedProperty radialGradientStrengthProperty;
    public SerializedProperty angleGradientStrengthProperty;
    public SerializedProperty proceduralGradientAngleProperty;
    public SerializedProperty sdfGradientInnerDistanceProperty;
    public SerializedProperty sdfGradientOuterDistanceProperty;
    public SerializedProperty sdfGradientInnerReachProperty;
    public SerializedProperty sdfGradientOuterReachProperty;
    public SerializedProperty conicalGradientCurvatureProperty;
    public SerializedProperty conicalGradientTailStrengthProperty;
    public SerializedProperty noiseScaleProperty;
    public SerializedProperty noiseSeedProperty;
