    public SerializedProperty simpleCutoutXProperty;
    public SerializedProperty simpleCutoutYProperty;
    public SerializedProperty simpleCutoutZProperty;
    public SerializedProperty simpleCutoutWProperty;
    public SerializedProperty sdfCutoutChamferProperty;
    public SerializedProperty sdfCutoutChamferXProperty;
    public SerializedProperty sdfCutoutChamferYProperty;
    public SerializedProperty sdfCutoutChamferZProperty;
    public SerializedProperty sdfCutoutChamferWProperty;
