    public SerializedProperty primaryColorFadeProperty;
    public SerializedProperty cornerChamferProperty;
    public SerializedProperty cornerXChamferProperty;
    public SerializedProperty cornerYChamferProperty;
    public SerializedProperty cornerZChamferProperty;
    public SerializedProperty cornerWChamferProperty;
    public SerializedProperty collapsedCornerChamferProperty;
    public SerializedProperty cornerConcavityProperty;
    public SerializedProperty cornerXConcavityProperty;
    public SerializedProperty cornerYConcavityProperty;
    public SerializedProperty cornerZConcavityProperty;
    public SerializedProperty cornerWConcavityProperty;
    public SerializedProperty collapsedCornerConcavityProperty;
    public SerializedProperty collapseEdgeAmountProperty;
    public SerializedProperty collapseEdgeAmountAbsoluteProperty;
    public SerializedProperty collapseEdgePositionProperty;
    public SerializedProperty strokeProperty;
    public SerializedProperty softnessProperty;
    public SerializedProperty sizeModifierProperty;
    public SerializedProperty sizeModifierXProperty;
    public SerializedProperty sizeModifierYProperty;
    public SerializedProperty offsetProperty;
    public SerializedProperty offsetXProperty;
